-- 1. Create user_locations table for saved interest zones
CREATE TABLE IF NOT EXISTS public.user_locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  name TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Enable RLS for security
ALTER TABLE public.user_locations ENABLE ROW LEVEL SECURITY;

-- Set user policies
CREATE POLICY "Allow users to read their own locations"
  ON public.user_locations FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

CREATE POLICY "Allow users to insert their own locations"
  ON public.user_locations FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Allow users to delete their own locations"
  ON public.user_locations FOR DELETE
  TO authenticated
  USING (auth.uid() = user_id);

