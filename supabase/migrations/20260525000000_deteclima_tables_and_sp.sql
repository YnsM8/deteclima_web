-- Stored Procedure to save a weather query via RPC
CREATE OR REPLACE FUNCTION public.save_weather_query_sp(
  p_lat DOUBLE PRECISION,
  p_lon DOUBLE PRECISION,
  p_location_name TEXT,
  p_data_json JSONB
)
RETURNS VOID
LANGUAGE plpgsql
